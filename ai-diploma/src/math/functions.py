"""
Модуль с функциями для расчёта выручки склада.

Здесь мы описываем:
1. Функцию выручки (мы хотим её максимизировать)
2. Функцию ошибки (мы хотим её минимизировать)
"""

def revenue(price):
    """
    Выручка склада в зависимости от цены.
    
    Формула: Количество = 100 - 2 * price
             Выручка = price * количество
    
    Аргументы:
        price (float): цена за единицу товара
    
    Возвращает:
        float: выручка (чем больше, тем лучше)
    
    Пример:
        >>> revenue(10)  # цена 10 → количество 80 → выручка 800
    """
    # Чем выше цена, тем меньше покупают
    quantity = 100 - 2 * price
    
    # Выручка = цена × количество
    return price * quantity


def loss_function(price):
    """
    Функция ошибки (для градиентного спуска).
    
    Мы хотим найти максимум выручки, но градиентный спуск ищет минимум.
    Поэтому берём ОТРИЦАТЕЛЬНУЮ выручку (чем больше выручка, тем меньше ошибка).
    
    Аргументы:
        price (float): цена за единицу товара
    
    Возвращает:
        float: ошибка (чем меньше, тем лучше)
    
    Пример:
        >>> loss_function(10)  # -revenue(10) = -800
    """
    return -revenue(price)
