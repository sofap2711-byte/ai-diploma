"""
Модуль для работы с отчётами.
Сохраняет результаты проекта в текстовый файл.
"""

from datetime import datetime
from functions import PRODUCT_NAME, CURRENT_PRICE, CURRENT_REVENUE


def save_report(history, filename="data/project_report.txt"):
    """
    Сохраняет отчёт о проекте в текстовый файл.
    """
    first = history[0]
    last = history[-1]
    
    optimal_price = last["price"]
    max_revenue = last["revenue"]
    improvement = ((max_revenue - CURRENT_REVENUE) / CURRENT_REVENUE * 100)
    
    # Находим шаг, где выручка максимальна
    max_step = max(history, key=lambda x: x["revenue"])
    
    # Определяем, повышать или понижать цену
    if optimal_price > CURRENT_PRICE:
        action = "ПОВЫСИТЬ"
        action_emoji = "⬆️"
    elif optimal_price < CURRENT_PRICE:
        action = "СНИЗИТЬ"
        action_emoji = "⬇️"
    else:
        action = "ОСТАВИТЬ БЕЗ ИЗМЕНЕНИЙ"
        action_emoji = "➡️"
    
    report = f"""
╔════════════════════════════════════════════════════════════════════════════════╗
║                                                                                ║
║              📦  ОПТИМИЗАЦИЯ ЦЕНЫ ДЛЯ СКЛАДА  📦                              ║
║                                                                                ║
║                    ФИНАЛЬНЫЙ ОТЧЁТ ПО ПРОЕКТУ                                  ║
║                                                                                ║
╚════════════════════════════════════════════════════════════════════════════════╝

📅 Дата: {datetime.now().strftime("%d.%m.%Y %H:%M")}


═══════════════════════════════════════════════════════════════════════════════════
  1.  ЧТО МЫ ДЕЛАЛИ
═══════════════════════════════════════════════════════════════════════════════════

   📌 Задача:
      Найти оптимальную цену для товара, при которой выручка максимальна.

   📌 Товар:
      {PRODUCT_NAME}

   📌 Исходные данные:
      Текущая цена:     {CURRENT_PRICE:>12,.0f} руб.
      Текущая выручка:  {CURRENT_REVENUE:>12,.0f} руб.

   📌 Метод:
      Градиентный спуск — алгоритм, который используется для обучения нейросетей.

   📌 Формула:
      Количество = 100 - 0.001 × Цена
      Выручка = Цена × Количество


═══════════════════════════════════════════════════════════════════════════════════
  2.  ЧТО МЫ СДЕЛАЛИ
═══════════════════════════════════════════════════════════════════════════════════

   Шаг 1. Построили математическую модель зависимости спроса от цены.

   Шаг 2. Запустили градиентный спуск, который:
          - начал с цены {first["price"]:,.0f} руб.
          - сделал {len(history)} шагов
          - нашёл оптимальную цену

   Шаг 3. Построили 9 графиков для визуализации процесса.

   Шаг 4. Сравнили результаты ДО и ПОСЛЕ оптимизации.


═══════════════════════════════════════════════════════════════════════════════════
  3.  ЧТО МЫ ПОЛУЧИЛИ
═══════════════════════════════════════════════════════════════════════════════════

   📊 Результаты оптимизации:

   ┌─────────────────────────────────────────────────────────────────────────────┐
   │  Показатель              │  ДО           │  ПОСЛЕ         │  ИЗМЕНЕНИЕ    │
   ├─────────────────────────────────────────────────────────────────────────────┤
   │  Цена (руб.)             │  {CURRENT_PRICE:>10,.0f}    │  {optimal_price:>10,.0f}    │  {((optimal_price - CURRENT_PRICE) / CURRENT_PRICE * 100):>+7.1f}% │
   │  Выручка (руб.)          │  {CURRENT_REVENUE:>10,.0f}    │  {max_revenue:>10,.0f}    │  {improvement:>+7.1f}% │
   └─────────────────────────────────────────────────────────────────────────────┘

   🏆 ЛУЧШИЙ РЕЗУЛЬТАТ:
      Цена:    {max_step['price']:,.0f} руб.
      Выручка: {max_step['revenue']:,.0f} руб.
      Шаг:     {max_step['step']}


═══════════════════════════════════════════════════════════════════════════════════
  4.  ВЫВОДЫ И РЕКОМЕНДАЦИИ
═══════════════════════════════════════════════════════════════════════════════════

   ✅ Оптимальная цена для товара "{PRODUCT_NAME}" составляет {optimal_price:,.0f} руб.

   ✅ При этой цене выручка достигает {max_revenue:,.0f} руб.

   ✅ Это на {improvement:.1f}% больше, чем при текущей цене.

   💡 РЕКОМЕНДАЦИЯ:
      {action_emoji} {action} цену с {CURRENT_PRICE:,.0f} руб. до {optimal_price:,.0f} руб.
      Это позволит увеличить выручку на {improvement:.0f}%.

   ⚠️ ВНИМАНИЕ:
      При изменении цены до {optimal_price:,.0f} руб. количество
      покупателей изменится, но выручка вырастет за счёт оптимального
      соотношения цены и спроса.


═══════════════════════════════════════════════════════════════════════════════════
  5.  ЧТО МОЖНО СДЕЛАТЬ ДАЛЬШЕ
═══════════════════════════════════════════════════════════════════════════════════

   🔹 Добавить больше товаров из базы данных
   🔹 Учесть сезонность спроса
   🔹 Добавить анализ конкурентов
   🔹 Построить прогноз продаж на следующий месяц
   🔹 Сделать веб-интерфейс для менеджеров склада


═══════════════════════════════════════════════════════════════════════════════════
  6.  ИТОГ
═══════════════════════════════════════════════════════════════════════════════════

   🎯 Мы успешно применили математику к реальной задаче склада.
   🎯 Нашли оптимальную цену, которая увеличивает выручку.
   🎯 Проект готов к показу преподавателю!


╔════════════════════════════════════════════════════════════════════════════════╗
║                                                                                ║
║                    ✅  ПРОЕКТ ГОТОВ К ПОКАЗУ!  ✅                             ║
║                                                                                ║
╚════════════════════════════════════════════════════════════════════════════════╝
"""
    
    # Сохраняем в файл
    with open(filename, "w", encoding="utf-8") as file:
        file.write(report)
    
    print(f"\n✅ Отчёт сохранён в файл: {filename}")