"""
Модуль для работы с отчётами.

Сохраняет результаты проекта в текстовый файл.
"""

from datetime import datetime


def save_report(history, filename="data/project_report.txt"):
    """
    Сохраняет отчёт о проекте в текстовый файл.
    
    Аргументы:
        history (list): история шагов градиентного спуска
        filename (str): путь к файлу для сохранения
    """
    # Берём первый и последний шаг
    first = history[0]
    last = history[-1]
    
    # Улучшение выручки
    improvement = ((last["revenue"] - first["revenue"]) / abs(first["revenue"]) * 100)
    
    report = f"""
    ═══════════════════════════════════════════════════════════════
              ФИНАЛЬНЫЙ ОТЧЁТ ПО ПРОЕКТУ
    ═══════════════════════════════════════════════════════════════
    
    📌 ПРОЕКТ: Оптимизация цены для склада
    📅 ДАТА: {datetime.now().strftime("%d.%m.%Y %H:%M")}
    
    ──────────────────────────────────────────────────────────────
    📊 РЕЗУЛЬТАТЫ ОПТИМИЗАЦИИ
    ──────────────────────────────────────────────────────────────
    
    🏁 СТАРТ:
        Цена:    {first["price"]:.2f} руб.
        Выручка: {first["revenue"]:.2f} руб.
    
    🎯 ФИНИШ:
        Цена:    {last["price"]:.2f} руб.
        Выручка: {last["revenue"]:.2f} руб.
    
    📈 УЛУЧШЕНИЕ:
        Выручка выросла на {improvement:.1f}%
        Количество шагов: {len(history)}
    
    💡 ВЫВОД:
        Оптимальная цена составляет около {last["price"]:.1f} руб.
        При этом выручка достигает {last["revenue"]:.0f} руб.
    
    ═══════════════════════════════════════════════════════════════
    """
    
    # Сохраняем в файл
    with open(filename, "w", encoding="utf-8") as file:
        file.write(report)
    
    print(f"✅ Отчёт сохранён в файл: {filename}")